#!/usr/bin/env bash
# Copia la librería de eventos canónica (pkg/events y pkg/outbox) a cada
# servicio que la usa. Cada servicio es un módulo Go aparte y su Docker
# solo ve su propia carpeta, por eso no se importa pkg/ directamente
# (ver docs/adr/0001-libreria-de-eventos-copiada.md).
#
# Uso:
#   scripts/sync-eventlib.sh          # actualiza las copias
#   scripts/sync-eventlib.sh --check  # falla si alguna copia está desactualizada (CI)
#
# Nunca edites las copias (internal/events/*.go e internal/outbox/*.go):
# editá pkg/ y volvé a correr este script.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CHECK=false
[[ "${1:-}" == "--check" ]] && CHECK=true

# servicio:paquetes
TARGETS=(
  "education:events outbox"
  "human-promotion:events outbox"
  "dashboard:events"
  "notifications:events"
  "auth:events"
  "labor-integration:events outbox"
  "campaigns:events outbox"
)

render() { # $1=servicio $2=paquete $3=archivo fuente
  local svc="$1" pkg="$2" src="$3"
  local mod="buenvivir/${svc}"
  [[ "$svc" == "auth" ]] && mod="auth"
  printf '// Code generated by scripts/sync-eventlib.sh from pkg/%s/%s. DO NOT EDIT.\n\n' "$pkg" "$(basename "$src")"
  sed "s#\"buenvivir/pkg/#\"${mod}/internal/#g" "$src"
}

status=0
for target in "${TARGETS[@]}"; do
  svc="${target%%:*}"
  for pkg in ${target#*:}; do
    src_dir="$ROOT/pkg/$pkg"
    dst_dir="$ROOT/$svc/internal/$pkg"
    mkdir -p "$dst_dir"

    if $CHECK; then
      for src in "$src_dir"/*.go; do
        dst="$dst_dir/$(basename "$src")"
        if [[ ! -f "$dst" ]] || ! diff -q <(render "$svc" "$pkg" "$src") "$dst" >/dev/null; then
          echo "desactualizado: $svc/internal/$pkg/$(basename "$src")"
          status=1
        fi
      done
      continue
    fi

    # Borra solo los archivos generados (no toca producers/, consumers/
    # ni otros archivos propios del servicio en la carpeta).
    for old in "$dst_dir"/*.go; do
      [[ -f "$old" ]] && head -1 "$old" | grep -q '^// Code generated by scripts/sync-eventlib.sh' && rm "$old"
    done
    for src in "$src_dir"/*.go; do
      render "$svc" "$pkg" "$src" > "$dst_dir/$(basename "$src")"
    done
    echo "ok: $svc/internal/$pkg"
  done
done

if $CHECK && [[ $status -ne 0 ]]; then
  echo "Corré scripts/sync-eventlib.sh y commiteá las copias." >&2
fi
exit $status
